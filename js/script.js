let langInitialized = false;

function setLang(l){
  const elements = document.querySelectorAll("[data-i18n]");
  const menuItems = document.querySelectorAll("#langMenu div");
  const langLabel = document.getElementById("langLabel");
  const cards = document.querySelectorAll("[data-i18n-card]");

  // ✅ Active state in dropdown
  menuItems.forEach(item => item.classList.remove("active"));
  menuItems.forEach(item => {
    if(item.dataset.lang === l){
      item.classList.add("active");
    }
  });

  // ✅ FIRST LOAD (no animation)
  if(!langInitialized){
    elements.forEach(el => {
      const key = el.dataset.i18n;
      if (t[l][key]) el.textContent = t[l][key];
    });

    langLabel.textContent = l.toUpperCase();
    langInitialized = true;
    return;
  }

// fade OUT cards
cards.forEach(card => {
  card.style.opacity = 0;
});

setTimeout(() => {
  cards.forEach(card => {
    card.style.opacity = 1;
  });
}, 300);

  // ✅ Smooth animation (ONLY system we use)
  elements.forEach(el => {
    const key = el.dataset.i18n;
    if (t[l][key]) {
      fadeText(el, t[l][key]);
    }
  });

  fadeText(langLabel, l.toUpperCase());

  // ✅ Close dropdown
  document.getElementById("langMenu").style.display = "none";
}

function fadeText(element, newText, duration = 300) {
  element.style.opacity = 0;

  setTimeout(() => {
    element.textContent = newText;
    element.style.opacity = 1;
  }, duration);
}

function toggleLang(){
  const m=document.getElementById("langMenu");
  m.style.display=m.style.display==="block"?"none":"block";
}

